-- Fresh-project Data API table privileges for the whole RLS policy surface.
--
-- Measured on a freshly reset local project (pg_policies compared against
-- information_schema.role_table_grants): 38 tables (43 table/role pairs)
-- carry RLS policies but hold NO table DML privilege, so PostgREST answers
-- 401/403 before RLS is ever evaluated. Live proof: the built app 403s on user_roles,
-- selling_points, invoice_settings and permission_settings reads and 401s on
-- anon storefronts reads. Older Supabase projects only worked because they
-- accumulated implicit default grants; a clean deployment gets none.
--
-- RLS remains the authority; these grants only let authenticated requests
-- reach the scoped policies below (doctrine quoted from
-- 20261026120000_active_business_context_operational_rls.sql). This file
-- creates, drops and weakens no policy — grants only, never wider than what
-- each role's existing policy commands implement.
--
-- Why dynamic introspection instead of a hand-enumerated GRANT list: the
-- policy surface is partly generated by format() loops (20260419203929,
-- 20260904000100, 20261019160000) and partly declared TO PUBLIC
-- ("Anyone can read pathao_areas/cities/zones"), so an enumerated list can
-- silently drift from policy intent and a reviewer must re-derive the
-- cmd -> operation mapping for ~40 pairs. Deriving each grant from
-- pg_policies.cmd makes "grant exactly what the policies implement" a single
-- reviewable rule; supabase/tests/rls/api_table_grants_test.sql asserts the
-- same invariant so later policy changes cannot silently recreate the gap.
--
-- Expected result of the introspection block (from the measured probe):
--   anon, table-level SELECT only:
--     pathao_areas, pathao_cities, pathao_zones, product_variations,
--     storefronts, storefront_products, storefront_collections,
--     storefront_collection_products, storefront_pages
--   anon, products: column-level SELECT only (carve-out below)
--   authenticated, SELECT only:
--     consent_records, disposable_email_domains
--   authenticated, SELECT, INSERT, UPDATE, DELETE: every other table with
--     authenticated policies (audit_log, connectors, custom_roles,
--     customer_sources, invitations, invoice_settings, locations,
--     measurement_assignments, measurement_fields, measurement_groups,
--     measurement_size_presets, order_item_measurements, order_sources,
--     pathao_areas, pathao_cities, pathao_integrations, pathao_stores,
--     pathao_zones, permission_settings, product_sources, purchase_orders,
--     selling_points, storefront_collection_products, storefront_collections,
--     storefront_pages, storefront_products, supplier_products, suppliers,
--     user_custom_roles, user_permissions, user_roles, user_store_access, …)

DO $$
DECLARE
  v_policy record;
  v_role text;
BEGIN
  FOR v_policy IN
    SELECT p.tablename AS table_name,
           lower(r.role_name) AS policy_role,
           p.cmd AS policy_cmd
    FROM pg_policies p
    CROSS JOIN LATERAL unnest(p.roles) AS r(role_name)
    WHERE p.schemaname = 'public'
      -- products/anon SELECT stays column-scoped (cost_price carve-out below).
      AND NOT (p.tablename = 'products' AND p.cmd = 'SELECT'
               AND lower(r.role_name) IN ('anon', 'public'))
      -- app_config is function-only by design: 20261022120000 routes access
      -- through is_signup_open() and REVOKEs the table from every API role.
      -- signup_config_accessor_test.sql asserts NO role holds table-wide
      -- app_config SELECT (and a private sentinel key stays invisible), so an
      -- introspection-driven GRANT here would silently break that contract.
      AND p.tablename <> 'app_config'
  LOOP
    -- A TO PUBLIC policy covers both Data API roles; anything else (owners /
    -- definer-only policies such as TO postgres) is not API surface.
    FOREACH v_role IN ARRAY CASE WHEN v_policy.policy_role = 'public'
                                 THEN ARRAY['anon', 'authenticated']
                                 ELSE ARRAY[v_policy.policy_role] END
    LOOP
      IF v_role NOT IN ('anon', 'authenticated') THEN
        CONTINUE;
      END IF;
      EXECUTE format(
        'GRANT %s ON public.%I TO %I',
        CASE v_policy.policy_cmd
          WHEN 'ALL' THEN 'SELECT, INSERT, UPDATE, DELETE'
          ELSE v_policy.policy_cmd
        END,
        v_policy.table_name,
        v_role);
    END LOOP;
  END LOOP;
END $$;

-- products: keep the anon cost_price carve-out from 20260620172022
-- ("products: prevent anon from reading cost_price"). A table-level
-- GRANT SELECT cannot be column-restricted, so it would expose cost_price
-- again; anon instead receives the public catalog columns at column level.
-- The list is deliberately enumerated and complete: a newly added products
-- column must be granted here on purpose — api_table_grants_test.sql fails
-- until it is — or the carve-out design must be revisited as a team.
GRANT SELECT (
  id, store_id, woo_product_id, sku, slug, name, description,
  price, regular_price, sale_price, sale_price_from, sale_price_to,
  short_description, attributes, tags, weight, dimensions,
  stock_quantity, manage_stock, stock_status, backorders,
  barcode, category, image_url, image_urls, is_featured, is_active,
  sales_count, woo_updated_at, created_at, updated_at
) ON public.products TO anon;

-- service_role bypasses RLS but still needs table privileges on the
-- operational tables the Edge Functions already read and write (woo-sync,
-- woo-push, woo-webhook, storefront-checkout, storefront-sitemap, …).
-- Same style as 20261023100000_signup_service_role_grants.sql: explicit
-- grants for the verbs those functions use, nothing else. webhook_events
-- already carries GRANT ALL from 20260802065800/20260830000600; the repeat
-- is a harmless no-op kept for a uniform list.
GRANT SELECT, INSERT, UPDATE, DELETE ON
  public.orders, public.products, public.order_items, public.order_payments,
  public.order_timeline, public.stores, public.categories,
  public.product_categories, public.product_variations, public.customers,
  public.customer_aliases, public.pathao_areas, public.pathao_cities,
  public.pathao_integrations, public.pathao_stores, public.pathao_zones,
  public.pathao_store_links, public.pos_returns, public.pos_shifts,
  public.held_carts, public.sync_queue, public.webhook_events,
  public.order_item_measurements
  TO service_role;

-- service_role INSERTs into identity/serial columns also need USAGE on the
-- owning sequences (the reason 20261023100000 granted
-- signup_events_id_seq). Only sequences owned by the tables above are
-- touched; tables with plain uuid keys contribute nothing here.
DO $$
DECLARE
  v_seq record;
BEGIN
  FOR v_seq IN
    SELECT ns.nspname AS seq_schema, s.relname AS seq_name
    FROM pg_class t
    JOIN pg_namespace nt ON nt.oid = t.relnamespace
    JOIN pg_depend d ON d.refobjid = t.oid
      AND d.refclassid = 'pg_class'::regclass
      AND d.deptype = 'a'
    JOIN pg_class s ON s.oid = d.objid AND s.relkind = 'S'
    JOIN pg_namespace ns ON ns.oid = s.relnamespace
    WHERE nt.nspname = 'public'
      AND t.relkind IN ('r', 'p')
      AND t.relname = ANY (ARRAY[
        'orders', 'products', 'order_items', 'order_payments',
        'order_timeline', 'stores', 'categories', 'product_categories',
        'product_variations', 'customers', 'customer_aliases',
        'pathao_areas', 'pathao_cities', 'pathao_integrations',
        'pathao_stores', 'pathao_zones', 'pathao_store_links',
        'pos_returns', 'pos_shifts', 'held_carts', 'sync_queue',
        'webhook_events', 'order_item_measurements'
      ])
  LOOP
    EXECUTE format('GRANT USAGE ON SEQUENCE %I.%I TO service_role',
                   v_seq.seq_schema, v_seq.seq_name);
  END LOOP;
END $$;

